// Sound-effect designs. Each sound is one or more ZzFX voices mixed into a single buffer, then
// normalised to a target peak so the set stays cohesive. Pure data + a builder that only needs
// ZZFX.buildSamples (so it also runs offline in Node).
//
// ZzFX params: [volume, randomness, frequency, attack, sustain, release, shape, shapeCurve, slide,
//   deltaSlide, pitchJump, pitchJumpTime, repeatTime, noise, modulation, bitCrush, delay,
//   sustainVolume, decay, tremolo, filter]
